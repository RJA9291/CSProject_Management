// Bakes an SVG path of Malaysia (Natural Earth 1:50m via world-atlas, public domain)
// plus projected city points into src/assets/malaysiaMap.ts.
// Usage: node scripts/build-map.mjs
import {readFileSync, writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {geoMercator, geoPath} from 'd3-geo';
import {feature} from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8'));
const countries = feature(topo, topo.objects.countries).features;
const byId = (id) => countries.find((c) => c.id === id);

const W = 1000;
const H = 520;
const malaysia = byId('458');
const projection = geoMercator().fitExtent([[20, 20], [W - 20, H - 20]], malaysia);
const path = geoPath(projection);

const neighbours = ['360', '096', '702', '764', '608'] // Indonesia, Brunei, Singapore, Thailand, Philippines
  .map((id) => path(byId(id)))
  .filter(Boolean);

const cities = {
  'Kuala Lumpur': [101.69, 3.14], 'George Town': [100.33, 5.41], 'Johor Bahru': [103.76, 1.49],
  'Kota Kinabalu': [116.07, 5.98], Kuching: [110.36, 1.55], 'Kota Bharu': [102.24, 6.13],
  Ipoh: [101.08, 4.6], Kuantan: [103.33, 3.81], Melaka: [102.25, 2.19], 'Alor Setar': [100.37, 6.12],
  Sandakan: [118.07, 5.84], Miri: [113.99, 4.4], Seremban: [101.94, 2.73], 'Kuala Terengganu': [103.14, 5.33],
  Tawau: [117.89, 4.24], Sibu: [111.82, 2.29], Bintulu: [113.03, 3.17], 'Shah Alam': [101.53, 3.07],
};
const points = Object.fromEntries(
  Object.entries(cities).map(([k, v]) => [k, projection(v).map((n) => Math.round(n * 10) / 10)]),
);

const out = `// AUTO-GENERATED by scripts/build-map.mjs - do not edit by hand.
// Source: Natural Earth 1:50m (public domain) via the world-atlas package.
export const MAP_WIDTH = ${W};
export const MAP_HEIGHT = ${H};
export const MALAYSIA_PATH = ${JSON.stringify(path(malaysia))};
export const NEIGHBOUR_PATHS: string[] = ${JSON.stringify(neighbours)};
export const CITY_POINTS: Record<string, [number, number]> = ${JSON.stringify(points, null, 2)};
`;
writeFileSync(new URL('../src/assets/malaysiaMap.ts', import.meta.url), out);
console.log('malaysia path length', path(malaysia).length);
